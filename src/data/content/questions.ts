export function getQuestionBySlug(slug: string): Question | undefined {
  return questions.find((q) => q.slug === slug)
}

export function getRelatedQuestions(slug: string, limit = 4): Question[] {
  const q = getQuestionBySlug(slug)
  if (!q) return []
  const out: Question[] = []
  for (const rel of q.relatedSlugs) {
    const found = getQuestionBySlug(rel)
    if (found) out.push(found)
    if (out.length >= limit) break
  }
  return out
}

